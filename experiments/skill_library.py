def run_smoke(args):
    log.info("=== VOYAGER-SKILLLIB smoke (master seed %d) ===", MASTER_SEED)
    emb = Embedder()
    log.info("embedder: mode=%s dim=%d | generator=%s", emb.mode, emb.dim, GEN_MODEL)
    store = Store(args.store, emb)
    n = store.load()
    log.info("loaded %d existing skills from %s", n, args.store)

    train_cases = {t.tid: make_cases(t, 6, seed=100 + i) for i, t in enumerate(SEED_TASKS)}
    held_cases = {t.tid: make_cases(t, 8, seed=900 + i) for i, t in enumerate(HELDOUT_TASKS)}

    # ---- 0) NEGATIVE CONTROL: a wrong program must be REJECTED --------------
    log.info("--- negative control: verifier must reject a wrong program ---")
    wrong = "def solve(s):\n    return s\n"
    rc = verify_code(wrong, SEED_TASKS[0], train_cases["rev_str"])
    log.info("negative control (identity for reverse): ok=%s reason=%s  -> %s",
             rc["ok"], rc["reason"], "PASS(rejected)" if not rc["ok"] else "FAIL(accepted!)")
    assert not rc["ok"], "NEGATIVE CONTROL FAILED: verifier accepted a wrong program"
    try:
        store.add("rev_str", "text_reverse", "bogus", wrong, rc)
        raise AssertionError("PURITY FAILED: store accepted an unverified program")
    except ValueError as e:
        log.info("purity gate: %s  -> PASS", e)

    # ---- 1) GENERATE -> VERIFY -> STORE -------------------------------------
    log.info("--- phase 1: generate -> verify -> store (seed tasks, 1 attempt each) ---")
    stored, attempts = 0, 0
    for i, t in enumerate(SEED_TASKS):
        p = prompt_scratch(t)
        raw = ollama_generate(p, temperature=0.2, seed=MASTER_SEED + i)
        code = extract_code(raw)
        vr = verify_code(code, t, train_cases[t.tid])
        attempts += 1
        log.info("  [%s/%s] verified=%s (%d/%d) %s", t.tid, t.family, vr["ok"],
                 vr["n_pass"], vr["n_total"], vr["reason"][:70])
        if vr["ok"]:
            sk = store.add(t.tid, t.family, p, code, vr)
            stored += 1
            log.info("    stored skill_id=%s family=%s", sk.skill_id, sk.family)
    log.info("phase 1: %d/%d seed attempts verified+stored (library now %d skills)",
             stored, attempts, len(store.skills))
    assert stored >= 1, "no skill stored -- smoke cannot continue"

    # ---- 2) RETRIEVE for a semantically-similar LATER prompt ----------------
    log.info("--- phase 2: retrieve nearest skill for a later prompt ---")
    sim_task = HELDOUT_TASKS[0]  # rev_all_words, family text_reverse
    q = prompt_scratch(sim_task)
    hits = store.retrieve(q, top_k=3)
    for sk, s in hits:
        log.info("  rank=%d sim=%.4f skill=%s family=%s", hits.index((sk, s)) + 1, s,
                 sk.tid, sk.family)
    top_sk, top_sim = hits[0]
    log.info("  query family=%s | top-1 family=%s sim=%.4f -> %s",
             sim_task.family, top_sk.family, top_sim,
             "HIT" if top_sk.family == sim_task.family else "MISS")

    # ---- 3) REUSE -----------------------------------------------------------
    log.info("--- phase 3: reuse (verbatim + augmented) on the held-out task ---")
    vr_v = verify_code(top_sk.code, sim_task, held_cases[sim_task.tid])
    log.info("  verbatim reuse: verified=%s (%d/%d) %s",
             vr_v["ok"], vr_v["n_pass"], vr_v["n_total"], vr_v["reason"][:70])

    raw_a = ollama_generate(prompt_augmented(sim_task, top_sk), temperature=0.2,
                            seed=MASTER_SEED + 500)
    code_a = extract_code(raw_a)
    vr_a = verify_code(code_a, sim_task, held_cases[sim_task.tid])
    log.info("  augmented reuse: verified=%s (%d/%d) %s",
             vr_a["ok"], vr_a["n_pass"], vr_a["n_total"], vr_a["reason"][:70])
    raw_s = ollama_generate(prompt_scratch(sim_task), temperature=0.2,
                            seed=MASTER_SEED + 501)
    code_s = extract_code(raw_s)
    vr_s = verify_code(code_s, sim_task, held_cases[sim_task.tid])
    log.info("  scratch (no exemplar): verified=%s (%d/%d) %s",
             vr_s["ok"], vr_s["n_pass"], vr_s["n_total"], vr_s["reason"][:70])

    if vr_a["ok"]:
        try:
            store.add(sim_task.tid, sim_task.family, prompt_augmented(sim_task, top_sk),
                      code_a, vr_a)
            log.info("  stored the reused+adapted program as a NEW skill")
        except ValueError:
            pass

    # ---- purity re-audit ----------------------------------------------------
    bad = [s.skill_id for s in store.skills if not s.verified]
    log.info("purity re-audit: %d entries, %d unverified -> %s",
             len(store.skills), len(bad), "PASS" if not bad else "FAIL")

    ok = (stored >= 1 and top_sk.family == sim_task.family and not bad and not rc["ok"])
    log.info("SMOKE VERDICT: %s", "PASS" if ok else "FAIL")
    return ok


def run_full(args):
    log.info("=== VOYAGER-SKILLLIB full run (master seed %d, k=%d) ===",
             MASTER_SEED, args.k)
    emb = Embedder()
    log.info("embedder: mode=%s dim=%d | generator=%s", emb.mode, emb.dim, GEN_MODEL)
    store = Store(args.store, emb)
    store.load()

    train_cases = {t.tid: make_cases(t, 6, seed=100 + i) for i, t in enumerate(SEED_TASKS)}
    held_cases = {t.tid: make_cases(t, 8, seed=900 + i) for i, t in enumerate(HELDOUT_TASKS)}

    # phase 1 -- build the library
    stored = 0
    for i, t in enumerate(SEED_TASKS):
        p = prompt_scratch(t)
        raw = ollama_generate(p, temperature=0.2, seed=MASTER_SEED + i)
        vr = verify_code(extract_code(raw), t, train_cases[t.tid])
        log.info("  store[%s] verified=%s (%d/%d)", t.tid, vr["ok"], vr["n_pass"], vr["n_total"])
        if vr["ok"]:
            store.add(t.tid, t.family, p, extract_code(raw), vr)
            stored += 1
    log.info("library built: %d/%d stored", stored, len(SEED_TASKS))

    # gate (a) -- retrieval separation
    same, cross, hits, tot = [], [], 0, 0
    M = store.matrix()
    for i, t in enumerate(HELDOUT_TASKS):
        q = emb.embed(prompt_scratch(t))
        sims = M @ q
        for j, sk in enumerate(store.skills):
            (same if sk.family == t.family else cross).append(float(sims[j]))
        top = store.skills[int(np.argmax(sims))]
        hit = top.family == t.family
        hits += hit
        tot += 1
        reused = verify_code(top.code, t, held_cases[t.tid])
        log.info("  query[%s] family=%s top-1=%s(%s) sim=%.4f hit=%s verbatim_ok=%s",
                 t.tid, t.family, top.tid, top.family, float(np.max(sims)), hit, reused["ok"])
    F = len({t.family for t in SEED_TASKS})
    hit_rate = hits / tot if tot else 0.0
    chance = 1.0 / F
    a_ok = (hit_rate >= 0.60) and (hit_rate - chance >= 0.20)
    log.info("GATE (a) retrieval: hit_rate=%.3f chance=%.3f margin=%+.3f | same=%.4f cross=%.4f -> %s",
             hit_rate, chance, hit_rate - chance,
             float(np.mean(same)) if same else 0.0,
             float(np.mean(cross)) if cross else 0.0, "PASS" if a_ok else "FAIL")

    # gate (b) -- pass@k scratch vs augmented. The library is FROZEN during
    # evaluation; augmented successes are buffered and stored only afterwards.
    res = {"scratch": {}, "augmented": {}}
    pending_adds = []
    for ci, cond in enumerate(["scratch", "augmented"]):
        for ti, t in enumerate(HELDOUT_TASKS):
            ex = store.retrieve(prompt_scratch(t), 1)
            exemplar = ex[0][0] if ex else None
            passes, best = 0, None
            for i in range(args.k):
                pr = (prompt_scratch(t) if cond == "scratch"
                      else prompt_augmented(t, exemplar))
                raw = ollama_generate(pr, temperature=0.8, seed=MASTER_SEED + 1000 * (ci + 1) + 100 * ti + i)
                vr = verify_code(extract_code(raw), t, held_cases[t.tid])
                if vr["ok"]:
                    passes += 1
                    best = best or extract_code(raw)
                if vr["ok"] and cond == "augmented":
                    pending_adds.append((t.tid, t.family, pr, extract_code(raw), vr))
            res[cond][t.tid] = passes
            log.info("  %-10s %-14s pass@%d = %d", cond, t.tid, args.k, passes)
    for (tid, fam, pr, code, vr) in pending_adds:  # replay AFTER eval (frozen lib)
        try:
            store.add(tid, fam, pr, code, vr)
        except ValueError:
            pass
    if pending_adds:
        log.info("  stored %d augmented successes after eval (library now %d)",
                 len(pending_adds), len(store.skills))
    p_scratch = sum(1 for v in res["scratch"].values() if v >= 1) / len(HELDOUT_TASKS)
    p_aug = sum(1 for v in res["augmented"].values() if v >= 1) / len(HELDOUT_TASKS)
    flips = sum(1 for tid in res["scratch"]
                if res["scratch"][tid] < 1 <= res["augmented"][tid])
    b_ok = (p_aug - p_scratch >= 0.10) and flips >= 1
    log.info("GATE (b) reuse: pass@k scratch=%.3f augmented=%.3f delta=%+.3f flips=%d -> %s",
             p_scratch, p_aug, p_aug - p_scratch, flips, "PASS" if b_ok else "FAIL")
    log.info("  raw: scratch=%s augmented=%s", res["scratch"], res["augmented"])

    bad = [s.skill_id for s in store.skills if not s.verified]
    c_ok = not bad
    log.info("GATE (c) purity: %d entries, %d unverified -> %s",
             len(store.skills), len(bad), "PASS" if c_ok else "FAIL")
    log.info("VERDICT: a=%s b=%s c=%s", a_ok, b_ok, c_ok)
    return a_ok, b_ok, c_ok


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", choices=["smoke", "full"], default="smoke")
    ap.add_argument("--k", type=int, default=8)
    ap.add_argument("--store", default=os.path.join(ROOT, "results", "skill_library", "store.jsonl"))
    ap.add_argument("--fresh", action="store_true", help="wipe the store first")
    ap.add_argument("--log", default=None, help="also append logs to this file")
    args = ap.parse_args()

    if args.fresh and os.path.exists(args.store):
        os.remove(args.store)

    fmt = logging.Formatter("%(asctime)s %(levelname)s %(message)s", "%H:%M:%S")
    root = logging.getLogger()
    root.setLevel(logging.INFO)
    sh = logging.StreamHandler(sys.stdout)
    sh.setFormatter(fmt)
    root.addHandler(sh)
    if args.log:
        os.makedirs(os.path.dirname(args.log), exist_ok=True)
        fh = logging.FileHandler(args.log, mode="a")
        fh.setFormatter(fmt)
        root.addHandler(fh)

    if args.mode == "smoke":
        ok = run_smoke(args)
        sys.exit(0 if ok else 1)
    else:
        a, b, c = run_full(args)
        sys.exit(0 if (a and b and c) else 1)


if __name__ == "__main__":
    main()
