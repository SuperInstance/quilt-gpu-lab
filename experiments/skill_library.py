def _post(path: str, payload: dict, timeout: float = 240.0) -> dict:
    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(OLLAMA + path, data=data,
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read().decode("utf-8"))


def ollama_generate(prompt: str, model: str = GEN_MODEL, temperature: float = 0.2,
                    seed: Optional[int] = None, num_predict: int = 256) -> str:
    opts = {"temperature": temperature, "num_predict": num_predict, "top_p": 0.95}
    if seed is not None:
        opts["seed"] = int(seed)
    out = _post("/api/generate", {"model": model, "prompt": prompt,
                                  "stream": False, "options": opts})
    return out.get("response", "")


class Embedder:
    """nomic-embed-text via ollama, with a pure-python char-ngram TF-IDF fallback
    so the harness still runs if embeddings are unavailable. No external service."""

    def __init__(self, model: str = EMB_MODEL):
        self.model = model
        self.mode = "ollama"
        self._cache: dict[str, np.ndarray] = {}
        self._vocab: dict[str, int] = {}
        self._df: dict[str, int] = {}
        self._docs = 0
        try:
            v = self.embed_raw("probe")
            self.dim = len(v)
        except Exception as e:  # pragma: no cover
            log.warning("ollama embeddings unavailable (%s); using TF-IDF fallback", e)
            self.mode = "tfidf"
            self.dim = 4096

    # -- ollama path
    def embed_raw(self, text: str):
        out = _post("/api/embeddings", {"model": self.model, "prompt": text}, timeout=60.0)
        return np.asarray(out["embedding"], dtype=np.float32)

    # -- tfidf fallback
    @staticmethod
    def _toks(text: str):
        t = re.findall(r"[a-z0-9]+", text.lower())
        return t + [text.lower()[i:i + 4] for i in range(max(0, len(text) - 3))]

    def embed(self, text: str) -> np.ndarray:
        if text in self._cache:
            return self._cache[text]
        if self.mode == "ollama":
            v = self.embed_raw(text)
        else:
            v = self._tfidf(text)
        n = np.linalg.norm(v)
        v = v / n if n > 0 else v
        self._cache[text] = v
        return v

    def _tfidf(self, text: str) -> np.ndarray:
        v = np.zeros(self.dim, dtype=np.float32)
        for tk in self._toks(text):
            h = int(hashlib.md5(tk.encode()).hexdigest()[:8], 16) % self.dim
            v[h] += 1.0
        return v


# ----------------------------------------------------------------------------
# 3. VERIFIER -- pure code. Not an LLM. Negative-controls must FAIL here.
# ----------------------------------------------------------------------------

_ALLOWED = ["len", "range", "int", "str", "list", "dict", "set", "tuple", "sum", "abs",
            "min", "max", "sorted", "reversed", "enumerate", "zip", "map", "filter",
            "any", "all", "round", "float", "bool", "print", "ord", "chr", "divmod", "pow"]
SAFE_BUILTINS = {k: getattr(_builtins, k) for k in _ALLOWED}
SAFE_BUILTINS["__import__"] = None  # blocked


class VerifyTimeout(Exception):
    pass


def _on_alarm(signum, frame):  # pragma: no cover
    raise VerifyTimeout()


signal.signal(signal.SIGALRM, _on_alarm)

CODE_RE = re.compile(r"```(?:python)?\s*(.*?)```", re.S)


def extract_code(text: str) -> str:
    m = CODE_RE.search(text)
    if m:
        return m.group(1).strip()
    i = text.find("def ")
    return text[i:].strip() if i >= 0 else text.strip()


def verify_code(code: str, task: Task, testcases, entry_name: str = "solve",
                timeout_s: float = 3.0) -> dict:
    """EXECUTABLE verification. Returns dict(ok, reason, n_pass, n_total).
    Any exception / mismatch / timeout => ok=False."""
    res = {"ok": False, "reason": "", "n_pass": 0, "n_total": len(testcases), "elapsed": 0.0}
    if not code.strip():
        res["reason"] = "empty code"
        return res
    t0 = time.time()
    try:
        compile(code, "<candidate>", "exec")
    except SyntaxError as e:
        res["reason"] = f"syntax: {e}"
        return res
    ns = {"__builtins__": SAFE_BUILTINS}
    try:
        signal.setitimer(signal.ITIMER_REAL, timeout_s)
        exec(code, ns)  # noqa: S102 -- deliberate; restricted builtins + alarm guard
        fn = ns.get(entry_name)
        if not callable(fn):
            res["reason"] = f"no callable '{entry_name}' defined"
            return res
        for x, want in testcases:
            try:
                got = fn(x)
            except Exception as e:
                res["reason"] = f"runtime on {x!r}: {type(e).__name__}: {e}"
                return res
            if got != want:
                res["reason"] = f"mismatch on {x!r}: got {got!r} want {want!r}"
                return res
            res["n_pass"] += 1
        res["ok"] = True
        res["reason"] = "all tests passed"
    except VerifyTimeout:
        res["reason"] = f"timeout > {timeout_s}s"
    except Exception as e:  # noqa: BLE001
        res["reason"] = f"{type(e).__name__}: {e}"
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0)
    res["elapsed"] = round(time.time() - t0, 4)
    return res


# ----------------------------------------------------------------------------
# 4. STORE -- append-only JSONL; ONLY verified entries may enter (gate c).
# ----------------------------------------------------------------------------


@dataclass
class Skill:
    skill_id: str
    tid: str
    family: str
    prompt: str
    code: str
    verified: bool
    verify_reason: str
    n_pass: int
    emb_mode: str
    ts: float = field(default_factory=time.time)
    emb: Optional[list] = None


class Store:
    def __init__(self, path: str, embedder: Embedder):
        self.path = path
        self.embedder = embedder
        self.skills: list[Skill] = []
        os.makedirs(os.path.dirname(path), exist_ok=True)

    def add(self, tid: str, family: str, prompt: str, code: str, vres: dict) -> Skill:
        if not vres.get("ok"):
            raise ValueError("PURITY VIOLATION: refusing to store an unverified program")
        sid = hashlib.sha1((tid + "|" + code).encode()).hexdigest()[:12]
        sk = Skill(skill_id=sid, tid=tid, family=family, prompt=prompt, code=code,
                   verified=True, verify_reason=vres["reason"], n_pass=vres["n_pass"],
                   emb_mode=self.embedder.mode,
                   emb=self.embedder.embed(prompt).tolist())
        self.skills.append(sk)
        with open(self.path, "a") as f:
            f.write(json.dumps(asdict(sk)) + "\n")
        return sk

    def load(self) -> int:
        n = 0
        if not os.path.exists(self.path):
            return 0
        with open(self.path) as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                d = json.loads(line)
                if not d.get("verified"):  # gate (c)
                    raise ValueError(f"PURITY VIOLATION on load: {d.get('skill_id')}")
                self.skills.append(Skill(**d))
                n += 1
        return n

    def matrix(self):
        if not self.skills:
            return np.zeros((0, self.embedder.dim), dtype=np.float32)
        return np.vstack([np.asarray(s.emb, dtype=np.float32) for s in self.skills])

    def retrieve(self, query: str, top_k: int = 1):
        if not self.skills:
            return []
        q = self.embedder.embed(query)
        M = self.matrix()
        sims = M @ q
        order = np.argsort(-sims)[:top_k]
        return [(self.skills[i], float(sims[i])) for i in order]


# ----------------------------------------------------------------------------
# 5. GENERATION PROMPTS
# ----------------------------------------------------------------------------

SIG = "def solve({arg}):"


def prompt_scratch(task: Task) -> str:
    return (f"Write a Python function with this exact signature:\n\n"
            f"    {SIG.format(arg=task.argname)}\n\n"
            f"It must {task.spec}\n"
            f"Return ONLY the code inside a single ```python block. No tests, no explanation.")


def prompt_augmented(task: Task, exemplar: Skill | None) -> str:
    base = prompt_scratch(task)
    if exemplar is None:
        return base
    return (f"Here is a related, already-verified function for reference "
            f"(do not copy it blindly; adapt the idea):\n\n"
            f"Spec: {exemplar.prompt}\n```python\n{exemplar.code}\n```\n\n"
            f"Now, using the same style, solve this NEW task.\n\n{base}")


