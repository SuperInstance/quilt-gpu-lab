@dataclass
class Task:
    tid: str
    family: str
    kind: str  # "str" | "int" | "list"
    spec: str
    oracle: Callable
    argname: str


SEED_STR = ["hello world", "abc", "a man a plan a canal panama", "  spaced  out  ",
            "No NaMe HeRe", "xyzzy", "one two three four", "MiXeD CaSe WoRdS"]
SEED_INT = [0, 7, 42, 100, 909, 1234567, 55, 808]
SEED_LIST = [[3, 1, 2, 1, 3], [5, 5, 5], [9, 8, 7], [1, 2, 3, 4], [], [4, 4, 6, 6, 1], [10, -3, 10, 7], [2, 0, 8]]


def cases(kind: str, n: int, seed: int):
    """Deterministic test-case inputs for a kind. Values are drawn from a fixed
    pool then shuffled; kept small so verification is instant."""
    rng = np.random.default_rng(seed)
    pool = {"str": SEED_STR, "int": SEED_INT, "list": SEED_LIST}[kind]
    idx = rng.permutation(len(pool))
    out = [pool[i] for i in idx]
    while len(out) < n:
        out.append(out[len(out) % len(pool)])
    return out[:n]


