#!/usr/bin/env python3
"""VOYAGER-SKILLLIB -- minimal Voyager-style skill library (arXiv:2305.16291), no game env.

Mechanism:
    prompt -> GENERATE candidate program -> EXECUTABLE VERIFIER (pure code, no LLM judge)
           -> STORE verified program + embedding -> later prompt -> RETRIEVE nearest skill
           -> REUSE (augmented / verbatim).

Zero weight updates. Zero metered spend. CPU-only, local ollama only.

Gates (frozen in proposals/runs/VOYAGER-SKILLLIB-prereg.md):
    (a) retrieval top-1 family-hit >= 0.60 and >= 0.20 above chance (1/F)
    (b) augmented pass@k > scratch pass@k by >= 0.10, >= 1 task flipped fail->pass
    (c) library stores ONLY verified programs; wrong program must be rejected

NO COMMIT.
"""
